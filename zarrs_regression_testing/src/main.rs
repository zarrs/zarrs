//! Data compatibility testing between the current `zarrs` and previous releases.
//!
//! Arrays are written and read with the current `zarrs` and with previous releases (via helper binaries), for every combination of codec and data type.
//! Codec parameters, shapes and data are sampled with proptest.
//!
//! By default, only the latest release is tested and any regression results in a non-zero exit code.
//! With `--all`, every release is tested and a summary of how far back compatibility extends is printed.
//! With `--json <PATH>`, the cases and results are written as JSON (see [`zarrs_regression_testing::schema`]).
//! HTML reports of the results (e.g. for zarrs.dev) are generated by [`zarr_compatibility`](https://github.com/zarrs/zarr_compatibility).
//!
//! Subcommands make `zarrs` available to other tools (see `PROTOCOL.md`): `cases` writes the cases without running them, `serve` serves the helper protocol with the current `zarrs` or a release, and `build` builds release helpers.

#[cfg(target_endian = "big")]
compile_error!("array data is exchanged as native-endian bytes, but must be little-endian");

